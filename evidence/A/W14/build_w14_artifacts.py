"""Generate every W14 artifact from the delivered tools and the real captures.

Run with ``--check`` to verify the committed files still reproduce byte-for-byte.

Nothing here is typed by hand: every number comes from ``cg_w14_spatial``,
``cg_w14_sensor_qa`` and ``cg_w14_pairing`` reading the captures that are already
committed. The generator also refuses to write a report that claims non-movement,
labels one session a distribution, values a pairing tolerance, or puts a
developer's absolute path into a hash-pinned artifact - the four ways this week's
deliverables could mislead.
"""

