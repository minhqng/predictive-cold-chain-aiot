def build() -> dict[str, str]:
    if not H8_CAPTURE.is_file():
        raise SystemExit(f"missing required capture: {H8_CAPTURE}")

    spatial = sp.spatial_report(CAPTURES, MIN_SESSIONS)
    matrix = sp.ablation_matrix(CAPTURES, sp.ABLATION_VARIANTS, MIN_SESSIONS)
    qa_report = qa.position_qa(H8_CAPTURE, [H8_CAPTURE])
    qa.guard_no_forbidden_claim(qa_report)
    payload = pair.pairing_input(CAPTURES, MIN_SESSIONS)

    import io
    import json

    buffer = io.StringIO()
    import csv

    csv.writer(buffer, lineterminator="\n").writerows(sp.ablation_csv_rows(matrix))

    files: dict[str, str] = {
        "spatial-statistics.json": json.dumps(spatial, indent=2, sort_keys=True) + "\n",
        "spatial-report.md": _spatial_markdown(spatial),
        "ablation-support.json": json.dumps(matrix, indent=2, sort_keys=True) + "\n",
        "ablation-support.csv": buffer.getvalue(),
        "ablation-support.md": _ablation_markdown(matrix, payload),
        "sensor-position-qa.json": json.dumps(qa_report, indent=2, sort_keys=True) + "\n",
        "sensor-position-qa.md": _qa_markdown(qa_report),
        "pairing-input.json": json.dumps(payload, indent=2, sort_keys=True) + "\n",
        "member-b-handoff.md": _handoff_markdown(payload),
    }
    for name, text in files.items():
        guard_text(name, text)
    return files


def check_or_write(files: dict[str, str], write: bool) -> int:
    failures = []
    for name, text in sorted(files.items()):
        path = HERE / name
        if write:
            path.write_bytes(text.encode("utf-8"))
            print(f"wrote {name} ({len(text.encode('utf-8'))} bytes)")
        elif not path.is_file():
            failures.append(f"missing {name}")
        elif path.read_bytes() != text.encode("utf-8"):
            failures.append(f"differs: {name}")
    if failures:
        print("W14 ARTIFACTS: FAIL")
        for failure in failures:
            print(f"  - {failure}")
        return 1
    if not write:
        print(f"W14 ARTIFACTS OK ({len(files)} files reproduce from the tools and "
              f"captures)")
    return 0


def write_pins() -> int:
    """Pin every dossier file except the pin file itself, LF-only and sorted by name."""
    import hashlib

    lines = []
    for path in sorted(DOSSIER_FILES()):
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        lines.append(f"{digest}  {path.relative_to(HERE).as_posix()}\n")
    (HERE / "SHA256SUMS.txt").write_bytes("".join(lines).encode("utf-8"))
    print(f"wrote SHA256SUMS.txt ({len(lines)} files pinned)")
    return 0


