def guard_text(name: str, text: str) -> None:
    """The tool's own claim policy, applied to everything this generator writes."""
    try:
        qa.assert_no_false_claim(name, text)
    except rep.AnalysisError as error:
        raise SystemExit(f"refusing to write {error}")


def _spatial_markdown(spatial: dict[str, object]) -> str:
    capture = spatial["captures"][0]  # type: ignore[index]
    verdict = spatial["verdict"]  # type: ignore[assignment]
    lines = [
        "# W14 spatial statistics (A-W14-03)",
        "",
        "Generated by `evidence/A/W14/build_w14_artifacts.py` from committed captures. "
        "Nothing was measured for this report: no flash, no energized stage, no probe "
        "moved, and every figure below is host analysis of rows already in the "
        "repository.",
        "",
        "## Verdict",
        "",
        f"- independent thermal sessions on disk: **{verdict['independent_sessions']}** "
        f"(`boot_id` {capture['boot_ids'][0]}), each phase block labelled from its own "
        f"capture",
        f"- gradient distribution: **{spatial['gradient_distribution']['status']}** - a "
        f"distribution needs {spatial['gradient_distribution']['min_sessions_required']} "
        "independent sessions, so what is published instead is one session's per-sample "
        "series, labelled `SINGLE_SESSION_OBSERVATION`",
        f"- disturbance-specific spatial response: "
        f"**{spatial['disturbance_specific_response']['status']}**",
        f"- max pairwise air difference in the driven block: "
        f"**{capture['phases']['cooling']['air_gradient']['max_pairwise_difference_c']} C**, "
        "against **{} C** between an air probe and the hot-side surface".format(
            capture["phases"]["cooling"]["phase_max_pairwise_difference_c"]),
        "",
        "## What one session can and cannot say",
        "",
        "It can say how far apart the three chamber-air positions sat from each other "
        "while the bridge was driven, and how far the hot-side surface sat from them. "
        "It cannot say what the run-to-run spread of those quantities is, because one "
        "boot of one session carries no repetition; calling its sample dispersion a "
        "distribution would be the exact defect this deliverable exists to avoid.",
        "",
        "## Air gradients (T1 centre, T3 bottom, T4 near door)",
        "",
        "`sd_within_session_sample_c` is dispersion across samples **inside one run** "
        "(sample n-1). It is not a repeat spread and is not a tolerance.",
        "",
        "| phase | pair (roles) | n | mean C | sd within session C | min C | max C | "
        "max |dT| C | at device_ms |",
        "|---|---|---|---|---|---|---|---|---|",
    ]
    for phase in ("baseline", "cooling", "recovery"):
        block = capture["phases"].get(phase)  # type: ignore[union-attr]
        if not isinstance(block, dict) or "air_gradient" not in block:
            lines.append(f"| {phase} | no usable rows | - | - | - | - | - | - | - |")
            continue
        for label, pair_block in sorted(block["air_gradient"]["pairs"].items()):
            lines.append(
                f"| {phase} | {label} | {pair_block['n']} | {pair_block['mean_c']} | "
                f"{pair_block['sd_within_session_sample_c']} | {pair_block['min_c']} | "
                f"{pair_block['max_c']} | {pair_block['max_abs_c']} | "
                f"{pair_block['max_abs_device_ms']} |")
    lines += [
        "",
        f"Row accounting for the driven block: "
        f"`{capture['phases']['cooling']['air_gradient']['tallies']}` - a row missing "
        "one probe is counted, not averaged over.",
        "",
        "## Air versus the hot-side surface",
        "",
        "T2 sits on TEC metal (`TEC_HOT_SIDE`) and is never part of an air mean; it is "
        "reported here as a separation so the surface is visible without being "
        "averaged into air. The pairs below are labelled by what they are.",
        "",
        "| phase | pair (roles) | read as | n | mean C | max |dT| C |",
        "|---|---|---|---|---|---|",
    ]
