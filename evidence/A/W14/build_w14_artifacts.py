        "",
        f"- one `boot_id` ({capture['boot_ids'][0]}) across {capture['rows']} rows, so "
        "baseline, cooling and recovery are segments of one session, not three runs",
        "- `current_status`/`voltage_status` are empty in every row and `power_w`/"
        "`energy_wh` have no status column, so no electrical figure is status-checked",
        "- `device_ms` is per-boot; host wall-clock is not device time",
        "- the `#CG H8S schema=3` frames carry no sensor ROM ids, so a channel is a "
        "slot name, not a proven physical probe",
        "- the 2026-11-02 touch session is classed `PROBE_IDENTIFICATION` and is "
        "excluded from every number above",
        "",
        "## Reproduce",
        "",
        "```bash",
        f"py firmware/tools/cg_w14_spatial.py {rep.capture_id(H8_CAPTURE)} "
        f"--min-sessions {MIN_SESSIONS}",
        "py evidence/A/W14/build_w14_artifacts.py --check",
        "py evidence/A/W14/validate_w14.py",
        "```",
        "",
