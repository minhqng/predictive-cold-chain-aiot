"""Verify the W11 evidence dossier.

    py evidence/A/W11/validate_w11.py

Checks, in order:

1. every file in ``SHA256SUMS.txt`` exists, hashes to the pinned value, and every
   file the manifest promises is pinned; the pin set is exactly the dossier's
   deliverable file set - a file that ships unpinned fails, and a ``__pycache__``
   or ``.pyc`` entry that got pinned fails;
2. no artifact carries an absolute developer path;
3. every derived artifact reproduces byte-for-byte from the delivered tooling;
4. the S4 claims are re-derived here, not trusted: the real capture is parsed
   again, the divergence counts and the disagreement candidates are recomputed and
   compared, and the intent lane must still be empty in every committed source;
5. the fail-closed verdicts are still fail-closed: zero command observations
   proves zero legs (not a clean thermal leg), no S4 run is publishable, no lane
   source is ``INFERRED_FROM_INTENT``, and the fixture stays non-physical;
6. the S3 verdict is still NO-GO with the instrumentation reason, and the run
   expansion list still reports zero additional valid runs;
7. the thermal lane still rests on the W09-frozen geometry with the docs/01
   823-825 naming discrepancy written down, and every lane comparison still
   accounts for its rows - scanned = compared + excluded, each exclusion named;
8. the S3 deliverable still states what a session must record, and its per-capture
   shortfall table still covers exactly the W09 registry's captures with a reason
   for every required measurement and no capture promoted to S3-capable.

Exit code 0 only when every check passes. Nothing here touches hardware.
"""

from __future__ import annotations

import hashlib
import json
import pathlib
import re
import sys

DOSSIER = pathlib.Path(__file__).resolve().parent
REPO_ROOT = DOSSIER.parents[2]
TOOLS = REPO_ROOT / "firmware" / "tools"
sys.path.insert(0, str(TOOLS))
sys.path.insert(0, str(DOSSIER))

import build_w11_artifacts as builder  # noqa: E402
import cg_s4_refusal as refusal  # noqa: E402
import cg_w09_capture_parser as cp  # noqa: E402
import cg_w11_s3_feasibility as s3  # noqa: E402
import cg_w11_s4 as s4  # noqa: E402

ABSOLUTE_PATH = re.compile(r"(?:^|[\s\"'`(])[A-Za-z]:[\\/]{1,2}[^\s\"'`]*|[\\s\"'`(]/(?:home|Users)/")
FORBIDDEN_OVERSTATEMENT = re.compile(
    r"\bW11 (PASS|GREEN|COMPLETE|CLOSED)\b|\bS4 run (was )?(verified|proven|collected)\b",
    re.IGNORECASE,
)


def sha256(path: pathlib.Path) -> str:
    digest = hashlib.sha256()
    with path.open("rb") as handle:
        for block in iter(lambda: handle.read(1 << 20), b""):
            digest.update(block)
    return digest.hexdigest()


def read_json(rel: str) -> dict:
    return json.loads((DOSSIER / rel).read_text(encoding="utf-8"))


def is_cache(rel: str) -> bool:
    parts = rel.split("/")
    return "__pycache__" in parts or parts[-1].endswith(".pyc")


def pin_set_failures(pinned: set[str], on_disk: list[str]) -> list[str]:
    """The pin set must be exactly the dossier's deliverable file set.

    ``on_disk`` is every file present in the dossier, repository-relative and
    forward-slashed. A file that ships without a hash is an unverifiable artifact;
    a ``__pycache__`` or ``.pyc`` entry that *has* a hash means the manifest was
    generated by globbing a dirty tree. The pin file never pins itself.
    """
    failures: list[str] = []
    for name in sorted(pinned):
        if is_cache(name):
            failures.append(f"{name} is a build cache, not evidence - it may never be pinned")
        if name == "SHA256SUMS.txt":
            failures.append("SHA256SUMS.txt must not pin itself")
    for rel in sorted(on_disk):
        if rel == "SHA256SUMS.txt" or is_cache(rel):
            continue
        if rel not in pinned:
            failures.append(f"{rel} is present in the dossier but not hash-pinned")
    return failures


def geometry_failures(basis: dict) -> list[str]:
    """The thermal lane may only use the W09-frozen chamber-air slots.

    Two separate rules, both fail-closed: T2 (the TEC hot side) never enters a
    chamber-air statistic, and the docs/01 823-825 naming discrepancy stays written
    down. A dossier that quietly remapped the probes would look self-consistent
    while measuring a different box than the rest of the project.
    """
    failures: list[str] = []
    if not basis:
        return ["the artifact no longer states which slots carry the thermal lane"]
    if "t2" in basis.get("chamber_air_slots", []):
        failures.append("the TEC hot side re-entered the chamber-air slots")
    if "docs/01 lines 823-825" not in str(basis.get("docs01_discrepancy", "")):
        failures.append(
            "the docs/01 823-825 probe-naming discrepancy is no longer documented - "
            "silently remapping a slot would measure a different box than the project expects"
        )
    if "FROZEN_SENSOR_GEOMETRY" not in str(basis.get("reused_not_rederived", "")):
        failures.append("the geometry was re-derived here instead of reusing the W09 authority")
    if "no geometry field" not in str(basis.get("registry_gap", "")):
        failures.append(
            "the W09 registry gap this dossier had to work around is no longer reported"
        )
    return failures


def row_account_failures(account: dict, label: str) -> list[str]:
    """Every scanned row is either compared or excluded under a name.

    A row that vanishes from a statistic without a reason makes the published
    number describe a different population than the capture, which is the same
    defect as believing it.
    """
    failures: list[str] = []
    if not account:
        return [f"{label}: no row account is published, so exclusions cannot be checked"]
    if account.get("rows_compared", 0) + account.get("rows_excluded_total", 0) != account.get(
        "frames_scanned"
    ):
        failures.append(
            f"{label}: {account.get('frames_scanned')} scanned rows do not reconcile against "
            f"{account.get('rows_compared')} compared + {account.get('rows_excluded_total')} excluded"
        )
    unnamed = [
        reason for reason in account.get("rows_excluded", {})
        if reason not in s4.EXCLUSION_REASONS and reason not in s4.DUTY_EXCLUSION_REASONS
    ]
    if unnamed:
        failures.append(f"{label}: rows excluded under an unnamed reason: {unnamed}")
    return failures


def s3_shortfall_failures(published: list[dict], recomputed: list[dict],
                          registry_capture_ids: list[str]) -> list[str]:
    """The per-capture S3 shortfall table is re-derived, not trusted.

    Three rules: the table covers exactly the captures the W09 registry registers, no
    capture is promoted to S3-capable, and every required measurement is accounted for
    per capture with a reason - so 'no S3 data exists' stays a checked statement about
    each source instead of a claim about the repository.
    """
    failures: list[str] = []
    if [e["capture_id"] for e in published] != registry_capture_ids:
        failures.append(
            "the S3 shortfall table no longer covers the W09 registry's captures in order"
        )
    if published != recomputed:
        failures.append("the published S3 per-capture shortfalls are not what the registry says")
    required_ids = [m["id"] for m in s3.REQUIRED_MEASUREMENTS]
    for entry in published:
        if entry["could_support_an_s3_run"]:
            failures.append(f"{entry['capture_id']}: promoted to S3-capable without instrumentation")
        if sorted(entry["falls_short_of"]) != sorted(required_ids):
            failures.append(
                f"{entry['capture_id']}: the shortfall is not accounted for every required "
                "measurement, so a missing check is being reported as a passed one"
            )
        if set(entry["shortfall_reasons"]) != set(entry["falls_short_of"]):
            failures.append(f"{entry['capture_id']}: a shortfall has no reason attached")
        if entry["measurements_it_could_supply"]:
            failures.append(
                f"{entry['capture_id']}: {entry['measurements_it_could_supply']} listed as "
                "supplied although no S3 measurement exists on this hardware"
            )
    return failures


def main() -> int:
    failures: list[str] = []

    sums_path = DOSSIER / "SHA256SUMS.txt"
    if not sums_path.is_file():
        print("FAIL: SHA256SUMS.txt is missing")
        return 1

    pinned: dict[str, str] = {}
    for line in sums_path.read_text(encoding="utf-8").splitlines():
        match = re.match(r"^([0-9a-f]{64})  (.+)$", line.strip())
        if not match:
            failures.append(f"SHA256SUMS.txt: unparsable line {line!r}")
            continue
        pinned[match.group(2)] = match.group(1)

    for name, digest in sorted(pinned.items()):
        path = DOSSIER / name
        if not path.is_file():
            failures.append(f"{name} is pinned but missing")
        elif sha256(path) != digest:
            failures.append(f"{name} does not hash to the pinned value")

    for name in builder.PINNED_FILES:
        if name not in pinned:
            failures.append(f"{name} is not hash-pinned")

    # --- the pin set is exactly the dossier's deliverable file set -------------
    # A file that ships with the dossier but is not pinned is an unpinned,
    # un-verifiable artifact; a build cache that *is* pinned means the manifest was
    # generated by globbing a dirty tree. Both are defects, both fail closed.
    on_disk = [
        path.relative_to(DOSSIER).as_posix()
        for path in DOSSIER.rglob("*") if path.is_file()
    ]
    failures.extend(pin_set_failures(set(pinned), on_disk))

    for name in pinned:
        if not name.endswith((".md", ".json", ".csv", ".py", ".txt")):
            continue
        body = (DOSSIER / name).read_text(encoding="utf-8")
        hit = ABSOLUTE_PATH.search(body)
        if hit:
            failures.append(f"{name} carries a non-repository-relative path: {hit.group(0)!r}")
        if name.endswith(".md") and FORBIDDEN_OVERSTATEMENT.search(body):
            failures.append(f"{name} overstates S4 or the week as physically proven")

    for name, text in builder.build_artifacts().items():
        path = DOSSIER / name
        if not path.is_file():
            failures.append(f"{name} is not on disk")
        elif path.read_text(encoding="utf-8", newline="\n") != text:
            failures.append(f"{name} does not reproduce from the delivered tooling")

    frames, _ = cp.read_csv_capture(builder.W04_CSV, builder.RUN_LABEL)
    trace = s4.build_s4_trace(frames, is_physical_measurement=True)
    published_trace = read_json("s4-s3/s4-trace-real-capture.json")
    lane = read_json("s4-s3/lane-evidence.json")
    index = read_json("S4-runs/index.json")
    log = read_json("s4-s3/refusal-analysis-real-log.json")
    fixture = read_json("S4-runs/host-fixture-refusal-trace.json")
    feasibility = read_json("s4-s3/s3-feasibility.json")
    run_list = read_json("additional-valid-run-list.json")

    if trace["commands_observed"] != published_trace["commands_observed"]:
        failures.append("the published command-observation count is not the measured one")
    if trace["commands_observed"] != 0:
        failures.append("a command observation appears in the committed capture while the "
                        "dossier still claims none exists")
    recomputed_divergence = s4.request_applied_divergence(frames)
    if lane["request_applied_divergence"] != recomputed_divergence:
        failures.append("the three-lane divergence is not what the frames say")
    failures.extend(geometry_failures(lane.get("chamber_air_slot_basis")))
    failures.extend(row_account_failures(
        lane["request_applied_divergence"].get("row_account"), "duty-triple comparison"
    ))
    failures.extend(row_account_failures(
        lane["command_electrical_disagreements"].get("row_account"), "applied/current comparison"
    ))
    if lane["request_applied_divergence"].get("intent_vs_application", "").startswith(
        "SEPARABLE"
    ):
        failures.append(
            "the duty divergence was restated as separating intent from application, which "
            "zero command observations cannot do"
        )
    recomputed_candidates = s4.find_command_electrical_disagreements(frames)
    published_seqs = sorted(
        c["seq"] for c in lane["command_electrical_disagreements"]["no_active_response_candidates"]
    )
    measured_seqs = sorted(
        c["seq"] for c in recomputed_candidates["no_active_response_candidates"]
    )
    if published_seqs != measured_seqs:
        failures.append(
            f"no-active-response candidates {published_seqs} are not the measured {measured_seqs}"
        )
    for candidate in lane["command_electrical_disagreements"]["no_active_response_candidates"] + \
            lane["command_electrical_disagreements"]["residual_response_candidates"]:
        if candidate["electrically_qualified"]:
            failures.append(
                f"frame {candidate['seq']} was certified electrically although its "
                "current_status is empty"
            )

    for lane_record in fixture["command_row"]["lane_sources"].values():
        if lane_record in s4.FORBIDDEN_SOURCES:
            failures.append("an artifact carries an intent-derived device lane")
    if fixture["is_physical_measurement"] is not False:
        failures.append("the refusal fixture is presented as device evidence")
    if not fixture["an_intentional_promotion_raises"].startswith("PromotionError"):
        failures.append("the promotion rule is no longer demonstrably enforced")
    if json.dumps(fixture["command_row"]).count("REFUSED_NON_APPLICATION_OBSERVED") != 1:
        failures.append("the refusal fixture no longer reports non-application")

    if log["summary"]["cmdack_lines"] != 0:
        failures.append("the audited device log now has command lines and the dossier "
                        "was not re-derived")
    if log["score"]["thermal_non_response_proven"]:
        failures.append(
            "zero command observations were scored as proving thermal non-response - a missing "
            "field read as a satisfied condition"
        )
    if log["score"]["s4_run_publishable"] or index["publishable_run_count"]:
        failures.append("an S4 run is published that the evidence does not support")
    if index["runs_available"] != 0:
        failures.append("the S4 run list invented a run")

    if feasibility["verdict"] != "NO-GO":
        failures.append("the S3 verdict was flipped without new instrumentation")
    if any(m["available_now"] for m in feasibility["required_measurements"]):
        failures.append("an S3 measurement is claimed available on the frozen hardware")
    for method in feasibility["candidate_methods"]:
        if method["verdict"] == "GO":
            failures.append(f"S3 candidate {method['method']!r} was accepted")
    if "no fan obstruction was invented" not in json.dumps(feasibility["not_done"]):
        failures.append("the S3 assessment no longer states what it refused to do")
    if not feasibility.get("session_record_requirements"):
        failures.append(
            "the S3 deliverable stopped stating what a session must record, which is the whole "
            "content of a methodology-only NO-GO"
        )
    failures.extend(s3_shortfall_failures(
        feasibility.get("existing_capture_shortfalls", []),
        builder.s3_capture_shortfalls(),
        [c["capture_id"] for c in json.loads(
            builder.W09_REGISTRY.read_text(encoding="utf-8"))["captures"]],
    ))

    if run_list["s1_runs_certified_valid"] != 0 or run_list["s2_pilot_disturbances_available"] != 0:
        failures.append("the run-expansion list invented additional valid runs")
    parseable = [c for c in run_list["captures"] if c["parseable_by_the_delivered_parser"]]
    if len(parseable) != 1:
        failures.append("the run-expansion list changed how many sources are parseable")
    for capture in run_list["captures"]:
        if not capture["parseable_by_the_delivered_parser"] and capture["frames_usable_per_scenario"]:
            failures.append(f"{capture['capture_id']}: usability published for an unparseable source")
        if capture["additional_s1_or_s2_runs_available"]:
            failures.append(f"{capture['capture_id']}: frames counted as new runs")

    prose = (DOSSIER / "README.md").read_text(encoding="utf-8") + \
        (DOSSIER / "acceptance.md").read_text(encoding="utf-8")
    for phrase in ("REAL DATA NOT AVAILABLE", "NO-GO", "NEED_USER_ACTION",
                   "no publishable S4 run"):
        if phrase not in prose:
            failures.append(f"the dossier no longer states {phrase!r}")

    if not failures:
        print(
            f"W11 DOSSIER: OK ({len(pinned)} pinned files, {len(frames)} frames re-read, "
            f"{trace['commands_observed']} command observations, 0 publishable S4 runs, "
            "S3 NO-GO intact)"
        )
        return 0

    print("W11 DOSSIER: FAIL")
    for failure in failures:
        print(f"  - {failure}")
    return 1


def s3_assess_label() -> str:
    return s3.assess()["status_label"]




if __name__ == "__main__":
    if hasattr(sys.stdout, "reconfigure"):
        sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.exit(main())
