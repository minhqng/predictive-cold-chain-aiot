"""ColdGuard ML package (Member B).

The W01 contracts (``ml/data-dictionary-v0.md``, ``ml/leakage-risk-register.md``,
``ml/artifact-convention.md``, ``ml/claim-data-matrix.md``) define what is
legal; W02 makes the data-side rules executable:

* ``observations`` — canonical sample identity, event-time semantics,
  QoS-1 dedup and boot-scoped ordering;
* ``synthetic`` — deterministic synthetic fixture runs (B-W02-01);
* ``splitting`` — grouped run-level splitting (B-W02-02);
* ``windows`` — causal run-bounded windows (B-W02-03);
* ``labels`` — horizon labels ``y_t(H)`` with explicit statuses (B-W02-04);
* ``manifests`` — manifest parsing and cross-bindings (B-W02-05);
* ``intake`` — source-aware real-schema intake and fail-closed admission
  (B-W04-01 / B-W04-05);
* ``evaluation_contract`` — EWT/AIW interfaces and the frozen metric
  hierarchy (B-W04-02 / B-W04-03 / B-W04-04);
* ``real_data_qa`` — diagnostic sampling/channel QA and deterministic
  physical-state plots over W04 captures (B-W05-01 … B-W05-04);
* ``timing_alignment`` — provenance-aware event alignment, clock/sequence
  diagnostics, bounded response helpers and duplicate-event handling
  (B-W06-01 … B-W06-04);
* ``plant_eda`` — W07 physical baseline EDA, qualified-run repeatability,
  confounding inventory and pairing candidate variables (B-W07-01 … B-W07-04).

No model fitting, feature registry, or score computation exists yet.
"""

